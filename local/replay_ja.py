# 見出しなど、語順の都合で個別に直すもの
EXACT: dict[str, str] = {
    "▶ 播放": "▶ 再生",
    "⏸ 暂停": "⏸ 一時停止",
    "播放": "再生",
    "暂停": "一時停止",
    "战斗": "戦闘",
    "本回合：": "このターン：",
}


def localize(html: str) -> str:
    """HTML の文言を日本語にする（長い語から順に置換）。"""
    for zh in sorted(EXACT, key=len, reverse=True):
        html = html.replace(zh, EXACT[zh])
    for zh in sorted(TERMS, key=len, reverse=True):
        html = html.replace(zh, TERMS[zh])
    return html.replace('<html lang="zh-CN">', '<html lang="ja">')


#: 置き換えても残った中国語（確認用）。空なら全部訳せている。
def leftovers(html: str) -> list[str]:
    import re

    seen: list[str] = []
    for m in re.finditer(r"[\u4e00-\u9fff]{2,}", html):
        if m.group(0) not in seen:
            seen.append(m.group(0))
    return seen
